//! Telemetry, pass statistics, and deterministic execution trace recording.

use std::fmt;

use crate::compiler::pass_diagnostic::PassDiagnosticReport;
use crate::opt::context::AnalysisId;
use crate::opt::pass::{PassId, SemanticDomain};

/// Status of an individual pass execution step.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum PassExecutionStatus {
    /// Pass completed successfully.
    Success,
    /// Pass execution or verification failed.
    Failed,
}

impl fmt::Display for PassExecutionStatus {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Success => write!(f, "Success"),
            Self::Failed => write!(f, "Failed"),
        }
    }
}

/// Deterministic record of an individual pass execution step within a pipeline.
///
/// Contains exclusively deterministic fields (no timestamps or durations) to enable
/// strict equality assertions across repeated runs.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct PassTraceStep {
    /// Zero-based sequence index in the pipeline execution.
    pub step_index: usize,
    /// Identifier of the pass.
    pub pass_id: PassId,
    /// Declared semantic domain.
    pub semantic_domain: SemanticDomain,
    /// Execution status.
    pub status: PassExecutionStatus,
    /// Whether the pass mutated the circuit.
    pub modified: bool,
    /// Analyses required prior to execution.
    pub required_analyses: Vec<AnalysisId>,
    /// Analyses invalidated by this pass.
    pub invalidated_analyses: Vec<AnalysisId>,
    /// Operation count prior to pass execution.
    pub initial_operations: usize,
    /// Operation count following pass execution.
    pub final_operations: usize,
}

/// Deterministic, reproducible execution trace of a pass manager pipeline run.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct PassExecutionTrace {
    /// Name of the circuit compiled.
    pub circuit_name: String,
    /// Ordered steps executed by the pipeline.
    pub steps: Vec<PassTraceStep>,
}

impl PassExecutionTrace {
    /// Creates a new empty trace for the given circuit.
    pub fn new(circuit_name: impl Into<String>) -> Self {
        Self {
            circuit_name: circuit_name.into(),
            steps: Vec::new(),
        }
    }

    /// Records an execution step into the deterministic trace.
    pub fn record_step(&mut self, step: PassTraceStep) {
        self.steps.push(step);
    }

    /// Returns the number of steps recorded in this trace.
    #[inline]
    pub fn len(&self) -> usize {
        self.steps.len()
    }

    /// Returns `true` if no steps were recorded.
    #[inline]
    pub fn is_empty(&self) -> bool {
        self.steps.is_empty()
    }

    /// Asserts deterministic identity against another execution trace.
    pub fn is_identical(&self, other: &Self) -> bool {
        self == other
    }
}

/// Detailed telemetry and metrics for an individual pass execution.
#[derive(Clone, Debug, PartialEq)]
pub struct PassStatistics {
    /// Identifier of the pass.
    pub pass_id: PassId,
    /// Pipeline execution index (0-based).
    pub execution_order: usize,
    /// Semantic domain of the pass.
    pub semantic_domain: SemanticDomain,
    /// Whether the circuit was modified.
    pub modified: bool,
    /// Execution outcome status.
    pub status: PassExecutionStatus,
    /// Measured execution duration in nanoseconds (optional telemetry).
    pub duration_ns: Option<u128>,
    /// Required analyses checked before execution.
    pub required_analyses: Vec<AnalysisId>,
    /// Analyses preserved by this pass.
    pub preserved_analyses: Vec<AnalysisId>,
    /// Analyses invalidated by this pass.
    pub invalidated_analyses: Vec<AnalysisId>,
    /// Number of operations in circuit before pass.
    pub initial_operations: usize,
    /// Number of operations in circuit after pass.
    pub final_operations: usize,
    /// Net change in operation count (`final_operations - initial_operations`).
    pub delta_operations: isize,
    /// Human-readable summary produced by the pass.
    pub summary: String,
}

/// Comprehensive report generated by a complete pipeline run in the [`PassManager`](crate::opt::pass_manager::PassManager).
#[derive(Clone, Debug)]
pub struct PassManagerReport {
    /// Name of the compiled circuit.
    pub circuit_name: String,
    /// Deterministic execution trace.
    pub trace: PassExecutionTrace,
    /// Detailed per-pass statistics.
    pub statistics: Vec<PassStatistics>,
    /// Total number of passes executed.
    pub total_passes_executed: usize,
    /// Number of passes that made mutations to the circuit.
    pub total_passes_modified: usize,
    /// Net change in total operations across the entire pipeline.
    pub total_delta_operations: isize,
    /// Cumulative execution duration in nanoseconds across all passes.
    pub total_duration_ns: Option<u128>,
    /// Detailed per-pass diagnostic reports conforming to Phase 71 schema.
    pub pass_diagnostics: Vec<PassDiagnosticReport>,
}

impl PassManagerReport {
    /// Returns `true` if all executed passes succeeded.
    pub fn is_success(&self) -> bool {
        self.statistics
            .iter()
            .all(|s| s.status == PassExecutionStatus::Success)
    }
}
